import math


def area(r):
    '''
    Принимает радиус r и возвращает площадь круга.

    Пример:
        area(2)
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Принимает радиус r и возвращает периметр круга.

    Пример:
        perimeter(3)
    '''
    return 2 * math.pi * r

