
def area(a, b):
    """
    Принимает длину а и ширину b прямоугольника 
    и возвращает его площадь

    Пример вызова:
    area(3, 4)
    Вывод: 12
    """
    return a * b


def perimeter(a, b):
    """
    Принимает длину а и ширину b прямоугольника
    и возвращает его периметр

    Пример вызова:
    perimeter(3, 4)
    Вывод: 14
    """
    return 2 * (a + b)
