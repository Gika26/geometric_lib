def area(a, b, c):
    """
    Принимает сторону a, b, c треугольника 
    и возвращает его площадь
    
    Пример вызова:
    area(3, 4, 5)
    Вывод: 6
    """
    p = (a + b + c) / 2
    return (p * (p - a) * (p - b) * (p - c)) ** (1/2)



def perimeter(a, b, c):
    """
    Принимает сторону a, b, c треугольника 
    и возвращает его периметр
    
    Пример вызова:
    perimeter(3, 4, 5)
    Вывод: 12
    """
    return (a + b + c)
